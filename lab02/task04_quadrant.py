# Лабораторная 2, задача 4
# Даны координаты точки, не лежащей на осях. Определить номер координатной четверти.
#   II  |  I
#  -----+-----
#  III  |  IV

x = float(input("x = "))
y = float(input("y = "))

if x == 0 or y == 0:
    print("Точка лежит на оси, четверть не определена")
elif x > 0 and y > 0:
    print("Четверть 1")
elif x < 0 and y > 0:
    print("Четверть 2")
elif x < 0 and y < 0:
    print("Четверть 3")
else:
    print("Четверть 4")
