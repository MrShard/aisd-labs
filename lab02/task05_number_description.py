# Лабораторная 2, задача 5
# Дано целое число. Вывести описание вида «отрицательное четное число»,
# «нулевое число», «положительное нечетное число».

n = int(input("Введите целое число: "))

if n == 0:
    print("нулевое число")
else:
    if n > 0:
        sign = "положительное"
    else:
        sign = "отрицательное"

    if n % 2 == 0:
        parity = "четное"
    else:
        parity = "нечетное"

    print(f"{sign} {parity} число")
