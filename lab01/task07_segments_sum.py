# Лабораторная 1, задача 7
# Даны три точки A, B, C на числовой оси. Найти длины отрезков AC и BC и их сумму.
# Длина отрезка на оси = модуль разности координат.

A = float(input("Координата точки A: "))
B = float(input("Координата точки B: "))
C = float(input("Координата точки C: "))

AC = abs(A - C)
BC = abs(B - C)

print(f"AC = {AC}")
print(f"BC = {BC}")
print(f"AC + BC = {AC + BC}")
