# Лабораторная 3, задача 5
# Дано вещественное A и целое N (> 0). Одним циклом найти
# 1 - A + A^2 - A^3 + ... ± A^N. Условный оператор не использовать.
# Идея: каждое следующее слагаемое = предыдущее * (-A), тогда знак чередуется сам.

A = float(input("A = "))
N = int(input("N = "))

total = 1.0
term = 1.0
for i in range(N):
    term *= -A
    total += term

print(f"Сумма = {total}")
