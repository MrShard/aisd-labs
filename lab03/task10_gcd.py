# Лабораторная 3, задача 10
# Даны целые положительные A и B. Найти НОД по алгоритму Евклида.
# Алгоритм: пока B != 0, заменяем (A, B) на (B, A % B). Когда B станет 0, ответ — A.

A = int(input("A = "))
B = int(input("B = "))

a, b = A, B
while b != 0:
    a, b = b, a % b

print(f"НОД({A}, {B}) = {a}")
